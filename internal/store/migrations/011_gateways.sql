CREATE TABLE gateways (
 id uuid PRIMARY KEY,
 device_id uuid NOT NULL UNIQUE REFERENCES devices(id),
 name text NOT NULL,
 hostname text NOT NULL UNIQUE,
 router_ip text NOT NULL,
 client_cidrs text NOT NULL DEFAULT '',
 ssh_port integer NOT NULL CHECK (ssh_port BETWEEN 1 AND 65535),
 ssh_user text NOT NULL,
 host_key_fingerprint text NOT NULL,
 host_key_policy text NOT NULL CHECK (host_key_policy IN ('manual','tofu')),
 ssh_auth_method text NOT NULL CHECK (ssh_auth_method IN ('key','password','saved_key')),
 ssh_key_id uuid REFERENCES ssh_keys(id),
 encrypted_credential bytea,
 encrypted_lan bytea NOT NULL,
 created_by uuid NOT NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 state text NOT NULL DEFAULT 'new' CHECK (state IN ('new','queued','running','checked','ready','failed')),
 kind text NOT NULL DEFAULT 'check' CHECK (kind IN ('check','deploy')),
 generation bigint NOT NULL DEFAULT 0,
 attempts integer NOT NULL DEFAULT 0,
 run_after timestamptz NOT NULL DEFAULT now(),
 run_token uuid,
 error text NOT NULL DEFAULT '',
 desired_profile_id uuid REFERENCES profiles(id),
 applied_profile_id uuid REFERENCES profiles(id),
 applied_at timestamptz,
 CHECK ((ssh_auth_method='saved_key' AND ssh_key_id IS NOT NULL AND encrypted_credential IS NULL)
 OR (ssh_auth_method<>'saved_key' AND ssh_key_id IS NULL AND encrypted_credential IS NOT NULL))
);
