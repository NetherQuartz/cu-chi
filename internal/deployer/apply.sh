set -eu
umask 077
server_id="$1"; image="$2"; port="$3"; generation="$4"; mode="$5"
exec 9>/run/lock/cuchi-awg.lock
flock -w 900 9
base="/opt/cu-chi/$server_id"
if [ "$mode" = deploy ]; then
 if ! command -v docker >/dev/null; then
  export DEBIAN_FRONTEND=noninteractive
  apt-get -o DPkg::Lock::Timeout=120 update >/dev/null
  apt-get -o DPkg::Lock::Timeout=120 install -y docker.io ca-certificates >/dev/null
 fi
 systemctl enable --now docker >/dev/null
fi
docker info >/dev/null
if docker container inspect cuchi-awg >/dev/null 2>&1; then
 [ "$(docker inspect -f '{{ index .Config.Labels "io.cuchi.server" }}' cuchi-awg)" = "$server_id" ] || { echo CUCHI_ERROR_foreign_container; exit 15; }
fi
install -d -m 700 "$base" "$base/config" "$base/probe"
if [ -f "$base/generation" ] && [ "$(cat "$base/generation")" -gt "$generation" ]; then echo CUCHI_ERROR_stale_generation; exit 16; fi
stage=$(mktemp -d "$base/stage.XXXXXX")
cleanup() {
 if [ "$(docker inspect -f '{{ index .Config.Labels "io.cuchi.server" }}' "cuchi-probe-$server_id" 2>/dev/null)" = "$server_id" ]; then docker rm -f "cuchi-probe-$server_id" >/dev/null 2>&1 || true; fi
 docker exec cuchi-awg awg syncconf awg0 /config/awg0.conf >/dev/null 2>&1 || true
 rm -rf "$stage"
 rm -f "$base/config/with-probe.conf" "$base/probe/probe.conf"
}
trap cleanup EXIT
# Only fixed filenames generated by the control plane are sent over stdin.
tar --no-same-owner -xf - -C "$stage"
docker pull "$image" >/dev/null
if ! docker network inspect cuchi-awg >/dev/null 2>&1; then docker network create --label "io.cuchi.server=$server_id" cuchi-awg >/dev/null; fi
[ "$(docker network inspect -f '{{ index .Labels "io.cuchi.server" }}' cuchi-awg)" = "$server_id" ] || { echo CUCHI_ERROR_foreign_network; exit 17; }
install -m 600 "$stage/awg0.conf" "$base/config/awg0.conf.new"
mv "$base/config/awg0.conf.new" "$base/config/awg0.conf"
install -m 600 "$stage/with-probe.conf" "$base/config/with-probe.conf"
install -m 600 "$stage/probe.conf" "$base/probe/probe.conf"
if docker container inspect cuchi-awg >/dev/null 2>&1; then
 old_image=$(docker inspect -f '{{.Config.Image}}' cuchi-awg)
 if [ "$old_image" != "$image" ]; then docker rm -f cuchi-awg >/dev/null; fi
fi
if ! docker container inspect cuchi-awg >/dev/null 2>&1; then
 docker run -d --name cuchi-awg --label "io.cuchi.server=$server_id" --restart unless-stopped --network cuchi-awg \
  --cap-drop ALL --cap-add NET_ADMIN --device /dev/net/tun --security-opt no-new-privileges \
  --read-only --tmpfs /run --tmpfs /tmp --sysctl net.ipv4.ip_forward=1 --sysctl net.ipv6.conf.all.disable_ipv6=1 \
  --log-driver json-file --log-opt max-size=10m --log-opt max-file=3 \
  -p "$port:51820/udp" -v "$base/config:/config:ro" "$image" >/dev/null
else docker start cuchi-awg >/dev/null; fi
ready=false
for i in $(seq 1 30); do
 if docker exec cuchi-awg test -f /run/cuchi-ready >/dev/null 2>&1; then ready=true; break; fi
 sleep 1
done
[ "$ready" = true ] || { echo CUCHI_ERROR_runtime_start_failed; exit 18; }
docker exec cuchi-awg awg --version | grep -q '3.1.20260812'
docker exec cuchi-awg amneziawg-go --version | grep -q '3.1.20260828'
docker exec cuchi-awg awg syncconf awg0 /config/with-probe.conf
# A second network namespace verifies encrypted traffic, forwarding, MTU and DNS.
docker run --rm --name "cuchi-probe-$server_id" --label "io.cuchi.server=$server_id" --network cuchi-awg \
 --cap-drop ALL --cap-add NET_ADMIN --device /dev/net/tun --security-opt no-new-privileges \
 --read-only --tmpfs /run --tmpfs /tmp -v "$base/probe:/config:ro" --entrypoint /usr/local/bin/cuchi-probe "$image" >/dev/null
# Do not persist the temporary probe peer or its private key.
docker exec cuchi-awg awg syncconf awg0 /config/awg0.conf
docker exec cuchi-awg awg show awg0 peers | sort > "$stage/actual-peers"
sort "$stage/peers" > "$stage/expected-peers"
cmp "$stage/actual-peers" "$stage/expected-peers"
printf '%s\n' "$generation" > "$base/generation.new"
mv "$base/generation.new" "$base/generation"
printf 'CUCHI_APPLY_OK\n'
